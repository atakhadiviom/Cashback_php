<?php

declare(strict_types=1);

namespace App\Services;

final class CpanelSettingsService
{
    private string $path;

    /** @var list<string> */
    private const KEYS = [
        'enabled',
        'host',
        'username',
        'api_token',
        'password',
        'domain',
        'app_root',
        'home_dir',
        'php_path',
    ];

    public function __construct(?string $path = null)
    {
        $this->path = $path ?? dirname(__DIR__, 2) . '/storage/cpanel_settings.php';
    }

    public function path(): string
    {
        return $this->path;
    }

    /**
     * @return array{
     *     enabled: bool,
     *     host: string,
     *     username: string,
     *     api_token: string,
     *     password: string,
     *     domain: string,
     *     app_root: string,
     *     home_dir: string,
     *     php_path: string
     * }
     */
    public function defaults(): array
    {
        return [
            'enabled' => false,
            'host' => '',
            'username' => '',
            'api_token' => '',
            'password' => '',
            'domain' => '',
            'app_root' => '',
            'home_dir' => '',
            'php_path' => '/usr/local/bin/ea-php81',
        ];
    }

    /**
     * Overlay values stored in storage/cpanel_settings.php (only keys present in the file).
     *
     * @return array<string, mixed>
     */
    public function overlay(): array
    {
        if (!is_file($this->path)) {
            return [];
        }

        $data = require $this->path;
        if (!is_array($data)) {
            return [];
        }

        $out = [];
        if (array_key_exists('enabled', $data)) {
            $out['enabled'] = (bool) $data['enabled'];
        }
        foreach (['host', 'username', 'api_token', 'password', 'domain', 'app_root', 'home_dir', 'php_path'] as $key) {
            if (!array_key_exists($key, $data)) {
                continue;
            }
            $out[$key] = trim((string) $data[$key]);
        }

        return $out;
    }

    /**
     * Effective settings: defaults ← config cpanel ← overlay.
     *
     * @return array{
     *     enabled: bool,
     *     host: string,
     *     username: string,
     *     api_token: string,
     *     password: string,
     *     domain: string,
     *     app_root: string,
     *     home_dir: string,
     *     php_path: string
     * }
     */
    public function all(): array
    {
        $fromConfig = \config_value('cpanel', []);
        if (!is_array($fromConfig)) {
            $fromConfig = [];
        }

        $merged = array_merge(
            $this->defaults(),
            $this->normalize($fromConfig, false),
            $this->overlay()
        );

        if ($merged['php_path'] === '') {
            $merged['php_path'] = '/usr/local/bin/ea-php81';
        }

        return $merged;
    }

    /**
     * Persist cPanel settings. Blank api_token / password keep previous overlay (or config) values.
     *
     * @param array<string, mixed> $data
     * @return array{
     *     enabled: bool,
     *     host: string,
     *     username: string,
     *     api_token: string,
     *     password: string,
     *     domain: string,
     *     app_root: string,
     *     home_dir: string,
     *     php_path: string
     * }
     */
    public function save(array $data): array
    {
        $current = $this->all();
        $normalized = $this->normalize($data, true);

        if ($normalized['api_token'] === '') {
            $normalized['api_token'] = (string) ($current['api_token'] ?? '');
        }
        if ($normalized['password'] === '') {
            $normalized['password'] = (string) ($current['password'] ?? '');
        }

        $dir = dirname($this->path);
        if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new \RuntimeException('Cannot create storage directory for cPanel settings.');
        }

        $export = var_export($normalized, true);
        $contents = "<?php\n\ndeclare(strict_types=1);\n\n// Generated by admin UI. Do not commit.\nreturn {$export};\n";

        if (file_put_contents($this->path, $contents, LOCK_EX) === false) {
            throw new \RuntimeException('Failed to write cPanel settings file.');
        }

        // Keep runtime config in sync for the rest of this request.
        if (!isset($GLOBALS['config']) || !is_array($GLOBALS['config'])) {
            $GLOBALS['config'] = [];
        }
        $base = $GLOBALS['config']['cpanel'] ?? [];
        if (!is_array($base)) {
            $base = [];
        }
        $GLOBALS['config']['cpanel'] = array_merge($base, $normalized);

        return $normalized;
    }

    public function hasApiToken(): bool
    {
        return trim((string) ($this->all()['api_token'] ?? '')) !== '';
    }

    public function hasPassword(): bool
    {
        return trim((string) ($this->all()['password'] ?? '')) !== '';
    }

    public function maskedTokenHint(): string
    {
        return $this->hasApiToken()
            ? 'توکن ذخیره شده است؛ برای تغییر مقدار جدید وارد کنید'
            : 'توکن API سی‌پنل را وارد کنید';
    }

    public function maskedPasswordHint(): string
    {
        return $this->hasPassword()
            ? 'رمز ذخیره شده است؛ برای تغییر مقدار جدید وارد کنید'
            : 'اختیاری — فقط در صورت نیاز به API2';
    }

    /**
     * @param array<string, mixed> $data
     * @return array{
     *     enabled: bool,
     *     host: string,
     *     username: string,
     *     api_token: string,
     *     password: string,
     *     domain: string,
     *     app_root: string,
     *     home_dir: string,
     *     php_path: string
     * }
     */
    private function normalize(array $data, bool $fromForm): array
    {
        $out = $this->defaults();

        if ($fromForm) {
            $out['enabled'] = !empty($data['enabled']);
        } elseif (array_key_exists('enabled', $data)) {
            $out['enabled'] = (bool) $data['enabled'];
        }

        foreach (['host', 'username', 'api_token', 'password', 'domain', 'app_root', 'home_dir', 'php_path'] as $key) {
            if (!array_key_exists($key, $data)) {
                continue;
            }
            $out[$key] = trim((string) $data[$key]);
        }

        if ($out['php_path'] === '') {
            $out['php_path'] = '/usr/local/bin/ea-php81';
        }

        // Drop unknown keys by returning only known structure.
        $filtered = [];
        foreach (self::KEYS as $key) {
            $filtered[$key] = $out[$key];
        }

        return $filtered;
    }
}
